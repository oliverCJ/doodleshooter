function normalizeLanguage(lang) {
  return SUPPORTED_LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;
}

function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : `{${key}}`);
}

export function createI18n(storage = localStorage) {
  let lang = normalizeLanguage(storage.getItem(LANGUAGE_STORAGE_KEY) || DEFAULT_LANGUAGE);
  return {
    get lang() { return lang; },
    setLanguage(nextLang) {
      lang = normalizeLanguage(nextLang);
      storage.setItem(LANGUAGE_STORAGE_KEY, lang);
      return lang;
    },
    t(key, params = {}) {
      const table = MESSAGES[lang] || MESSAGES[DEFAULT_LANGUAGE];
      const fallback = MESSAGES[DEFAULT_LANGUAGE] || {};
      return interpolate(table[key] ?? fallback[key] ?? key, params);
    },
  };
}

export function i18nMessages() {
  return MESSAGES;
}
